-- ========================================================
-- JavrelStore — Campos visuales editables y personalizaciones
-- Ejecutar una sola vez en el SQL Editor del proyecto Supabase.
--
-- La tabla `products` de producción usa el esquema:
--   id / title / image_url / category_id / original_price / description / stock
-- Este script agrega las columnas que faltan para persistir TODOS los campos
-- editables in-situ (marca, etiqueta, especificaciones, rating, reseñas y
-- destacado). Mientras no se ejecute, la app guarda esos campos en localStorage
-- y sincroniza el resto del producto con Supabase sin romper el guardado.
-- ========================================================

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS brand TEXT,
  ADD COLUMN IF NOT EXISTS badge TEXT,
  ADD COLUMN IF NOT EXISTS specs JSONB DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS rating NUMERIC DEFAULT 5.0,
  ADD COLUMN IF NOT EXISTS reviews INT DEFAULT 0,
  ADD COLUMN IF NOT EXISTS featured BOOLEAN DEFAULT false;

-- Tabla de personalizaciones visuales del editor (textos libres de la tienda).
CREATE TABLE IF NOT EXISTS public.store_customizations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT UNIQUE NOT NULL,
  value TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.store_customizations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir lectura publica de personalizaciones" ON public.store_customizations;
CREATE POLICY "Permitir lectura publica de personalizaciones"
  ON public.store_customizations FOR SELECT USING (true);

DROP POLICY IF EXISTS "Permitir escritura publica de personalizaciones" ON public.store_customizations;
CREATE POLICY "Permitir escritura publica de personalizaciones"
  ON public.store_customizations FOR ALL USING (true) WITH CHECK (true);
